"""Generate/check public rule pages, report schema and the compatible catalog extension."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

from schemasentry.assessment import Report
from schemasentry.catalog_models import CatalogEvidence
from schemasentry.registry import public_rules, rule_markdown

ROOT = Path(__file__).resolve().parents[1]


def json_text(payload: dict[str, Any]) -> str:
    return json.dumps(payload, ensure_ascii=False, indent=2) + "\n"


def generated_files() -> dict[Path, str]:
    rules = public_rules()
    files = {ROOT / f"docs/rules/{rule.rule_id}.md": rule_markdown(rule) for rule in rules}
    files[ROOT / "docs/rules/README.md"] = (
        "# Public rule reference\n\n"
        "Generated by `make docs` from the same metadata as `schemasentry rules` and `explain`. "
        "The M3 internal classifier still uses its original seven-rule registry. "
        "M4 assessment uses all ten rules.\n\n"
        "| Rule | Default base severity | Meaning |\n|---|---|---|\n"
        + "".join(
            f"| [{rule.rule_id}]({rule.rule_id}.md) | {rule.base_severity} | {rule.title} |\n"
            for rule in rules
        )
        + "\nEach report retains base severity, final risk, confidence "
        "and modifier evidence separately. "
        "No finding or exit 0 establishes general safety.\n"
    )
    report_schema = {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": "https://github.com/Shellghostt/SchemaSentry/schema/report-v1.schema.json",
        **Report.model_json_schema(by_alias=True),
    }
    # Library constructors can use defaults; the public wire document writes every field/null.
    for model_schema in (report_schema, *report_schema.get("$defs", {}).values()):
        if model_schema.get("type") == "object":
            model_schema["required"] = list(model_schema["properties"])
    files[ROOT / "docs/schema/report-v1.schema.json"] = json_text(report_schema)
    # Keep the hand-maintained M2 wire contract and its required/null fields intact.
    snapshot_path = ROOT / "docs/schema/snapshot-v1.schema.json"
    snapshot_schema = json.loads(snapshot_path.read_text("utf-8"))
    catalog_schema = CatalogEvidence.model_json_schema(by_alias=True)
    snapshot_schema["$defs"].update(catalog_schema.pop("$defs", {}))
    snapshot_schema["properties"]["catalogEvidence"] = {
        "anyOf": [catalog_schema, {"type": "null"}],
        "description": "Optional version-1 M4 catalog evidence. Omission/null means unknown.",
    }
    files[snapshot_path] = json_text(snapshot_schema)
    return files


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if generated files drift.")
    args = parser.parse_args()
    files = generated_files()
    stale = []
    for path, text in files.items():
        expected = text.encode("utf-8")
        if args.check:
            if not path.is_file() or path.read_bytes() != expected:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(expected)
    if stale:
        print("Generated documentation/schema drift; run make docs:")
        print("\n".join(stale))
        return 1
    action = "Checked" if args.check else "Generated"
    print(f"{action} {len(files)} public documentation/schema files.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
